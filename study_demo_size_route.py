"""Example 1 (route navigation): effect of the number of demonstrations.

The demonstrations are generated by a known policy (THETA_TRUE), so the true
satisfaction probability of every candidate formula under the demonstrator's
policy can be computed exactly. For each demonstration size, this script draws
independent demonstration sets and compares, for the nominal and the robust
method, the value reported for the selected formula with its true
satisfaction probability.

The robust winner is found exactly with pruning: since the worst-case value of
a formula never exceeds its nominal value, formulas are evaluated in
decreasing order of nominal value until no remaining formula can win.

Put this file next to RouteSelection.py. Output: study_demo_size_route.csv
"""
import csv
import time

import numpy as np

import RouteSelection as rs

DELTA = 4.0
SIZES = (20, 40, 80, 160, 320)
N_SETS = 50
TOL = 1e-9


def robust_winner(model, counts, theta_hat, nominal, delta, seed):
    best_f, best_v = None, -np.inf
    for f in sorted(nominal, key=nominal.get, reverse=True):
        if nominal[f] <= best_v:
            break
        v = rs.worst_case_multistart(f, counts, theta_hat, delta, model,
                                     batch_size=4, min_starts=8, min_hits=3,
                                     seed=seed)["val_wc"]
        if v > best_v:
            best_f, best_v = f, v
    return best_f, best_v


def main():
    model = rs.SatisfactionModel()
    true = model.all_values(rs.THETA_TRUE)
    rows = []
    t0 = time.time()
    for n in SIZES:
        for s in range(N_SETS):
            counts = rs.generate_demonstrations(n, rs.THETA_TRUE, seed=1000 + s)
            try:
                theta_hat = rs.mle(counts)
            except RuntimeError:          # MLE does not exist (separable data)
                rows.append(dict(n=n, set=s, mle_exists=False))
                continue
            nominal = model.all_values(theta_hat)
            f_nom = max(nominal, key=nominal.get)
            f_rob, v_rob = robust_winner(model, counts, theta_hat, nominal, DELTA, s)
            drop = rs.loglik(theta_hat, counts) - rs.loglik(rs.THETA_TRUE, counts)
            rows.append(dict(n=n, set=s, mle_exists=True,
                             nominal_winner=f_nom, nominal_value=nominal[f_nom],
                             nominal_true=true[f_nom],
                             robust_winner=f_rob, robust_value=v_rob,
                             robust_true=true[f_rob],
                             demonstrator_in_set=drop <= DELTA))
        print(f"N = {n} done ({time.time() - t0:.0f} s)", flush=True)

    keys = ["n", "set", "mle_exists", "nominal_winner", "nominal_value",
            "nominal_true", "robust_winner", "robust_value", "robust_true",
            "demonstrator_in_set"]
    with open("study_demo_size_route.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=keys)
        w.writeheader()
        w.writerows(rows)

    print("\nTrue satisfaction under the demonstrator's policy (top 3):")
    for f in sorted(true, key=true.get, reverse=True)[:3]:
        print(f"  {f:12s} {true[f]:.4f}")
    print(f"\n{'N':>4} {'MLE':>6} {'robust<=true':>13} {'nominal>true':>13} "
          f"{'true(nom) mean/worst':>22} {'true(rob) mean/worst':>22}")
    for n in SIZES:
        g = [r for r in rows if r["n"] == n and r["mle_exists"]]
        rob_ok = np.mean([r["robust_value"] <= r["robust_true"] + TOL for r in g])
        nom_over = np.mean([r["nominal_value"] > r["nominal_true"] + TOL for r in g])
        tn = [r["nominal_true"] for r in g]
        tr = [r["robust_true"] for r in g]
        print(f"{n:>4} {len(g):>3}/{N_SETS} {rob_ok:>12.0%} {nom_over:>13.0%} "
              f"{np.mean(tn):>14.3f} / {min(tn):.3f} {np.mean(tr):>14.3f} / {min(tr):.3f}")


if __name__ == "__main__":
    main()
