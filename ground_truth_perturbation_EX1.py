"""Ground-truth recovery with an optimal expert and a perturbed optimal expert
(Example 1, gridworld route model of RouteSelection.py).

This is ground_truth_perturbation.py rewritten for the model in which the
driver makes a decision in every cell and the policy class is Eq. (1),
pi_theta(a|s) ~ exp(theta^T f(s,a)), with features (progress, follow_road,
enter_C, stop).

For each ground-truth formula phi* (one at a time):

  Expert.  The best policy for phi* in the policy class, computed with the
      known transition probabilities of the MDP:
          theta*_phi = argmax_theta  P_H(phi* | pi_theta) - EXPERT_RIDGE * ||theta||^2.
      The small penalty selects, among the (nearly) optimal policies, the one
      closest to uniformly random. Behavior that phi* does not constrain stays
      random (e.g., stopping at a shop when phi* = F T), just as the optimal
      expert of the old route model split ties evenly between the two safe
      routes. The printed table compares P_H(phi* | theta*) with the in-class
      maximum.

  Step 1 (eps = 0): demonstrations are generated by pi_{theta*}.
  Step 2 (eps > 0): the PERTURBED expert. Start from the expert that, in every
      state, takes a uniformly random valid action with probability eps:
          pi_mix(a|s) = (1 - eps) * pi_{theta*}(a|s) + eps / |A(s)|.
      pi_mix is not of the form pi_theta, so it could never lie in
      Pi_delta(D). With PERTURBATION = "projected" (default) the demonstrator
      is the policy IN THE CLASS that behaves most like pi_mix:
          theta_eps = argmax_theta  E_{pi_mix}[ log pi_theta(a|s) ],
      i.e., the MLE from infinitely many demonstrations of pi_mix (expected
      state-action counts, computed exactly by a forward pass). Its
      satisfaction probabilities match those of pi_mix closely, and since it
      is in the class, it lies in Pi_delta(D) with the confidence of Remark 2.
      PERTURBATION = "mixture" uses pi_mix itself (previous version).

  For N demonstrations (SEEDS random datasets per setting) both methods select
  a formula from the candidate set CANDIDATES (by default the ground-truth
  formulas themselves; None = all formulas of the grammar):
      nominal: theta_hat = MLE, pick argmax_phi P_H(phi | pi_theta_hat)
      robust : pick argmax_phi min_{theta in Pi_delta(D)} P_H(phi | pi_theta)
  and each pick is compared with phi*:
      * relation: "= phi*", "implied by phi*" (phi* |= pick, i.e., a weaker
        formula), or "not implied";
      * true satisfaction of the pick under the expert's actual policy;
      * overestimation: the value reported for the pick exceeds its true
        satisfaction;
      * whether the demonstrator's parameter (theta* for eps = 0, theta_eps
        for eps > 0) lies in Pi_delta(D), i.e.,
        log L(theta_hat) - log L(demonstrator) <= DELTA
        (not defined for PERTURBATION = "mixture" with eps > 0);
      * whether the unperturbed optimal expert theta* lies in Pi_delta(D),
        i.e., the perturbed demonstrations are still consistent with it.

Implementation notes
  * Monotonicity (Reviewer 1's point): if phi |= psi then psi scores at least
    as high as phi, nominally and in the worst case. With first-in-list tie
    breaking, both methods therefore always pick a candidate that implies no
    other candidate (the weakest candidates, WEAKEST). For the full grammar
    these are the 6 single clauses; for the default candidate set they are
    F T, F C, F S and G !C. The nominal pick is computed over all candidates
    (and checked to be in WEAKEST); the robust pick is searched over WEAKEST
    only, which gives the same result with far fewer worst-case solves.
  * The MLE is computed in the same box |theta_i| <= THETA_BOX as the worst
    case. With a nearly deterministic expert, some actions may never be
    deviated from, and the unconstrained MLE of RouteSelection.mle diverges.
    When the MLE is interior, both give the same theta_hat (concave problem).
  * The worst case uses the multi-start IPOPT of
    RouteSelection.worst_case_multistart, with its default settings
    (at least 27 starts; 8 starts can miss the global minimum by ~1e-3),
    plus two changes:
      - starting points are placed with the covariance inv(-Hessian + I).
        When the expert never visits some states, a feature can be
        unidentified (zero Fisher information) and the Hessian is singular;
      - pruning: formulas are evaluated in decreasing order of nominal value,
        and a formula is abandoned as soon as one IPOPT run finds a value
        below the best worst-case value so far (it can no longer win).
    `python ground_truth_perturbation_route.py validate` compares this solver
    and the box MLE with the original functions of RouteSelection.py.
  * The run is parallel (N_WORKERS processes) and resumable: finished
    datasets are appended to OUT_FILE and skipped when the script is rerun.
    Delete OUT_FILE after changing any setting.

Put this file next to RouteSelection.py.
Usage:  python ground_truth_perturbation_route.py            (run + summary)
        python ground_truth_perturbation_route.py summary    (summary only)
        python ground_truth_perturbation_route.py validate   (solver checks)
"""
import collections
import csv
import itertools
import json
import os
import sys
import time
from multiprocessing import Pool

import cyipopt
import numpy as np
from scipy.optimize import minimize
from scipy.stats import norm, qmc

import RouteSelection as rs

# =============================================================================
# 1) EXPERIMENT SETTINGS
# -----------------------------------------------------------------------------
# DELTA        : radius of the uncertainty set Pi_delta(D), as in Example 1.
# EPSILONS     : perturbation levels; eps = 0 is Step 1 (optimal expert).
#                The perturbation acts at every step (about 20-30 decisions
#                per trajectory), so small values already change behavior.
#                Small values keep theta* in Pi_delta(D) (column
#                theta_star_in_set); larger N reveals larger perturbations.
# NS           : numbers of demonstrations (trajectories) per dataset.
# SEEDS        : number of random datasets per (phi*, eps, N).
# GROUND_TRUTHS: None = every formula of the grammar, or a list such as
#                ["F T", "(F T ^ G !C)"].
# CANDIDATES   : formulas both methods choose from. GROUND_TRUTHS = the same
#                list as the ground truths; None = all formulas of the grammar.
# EXPERT_RIDGE : penalty lambda in the definition of the expert (see top).
# PERTURBATION : "projected" (perturbed expert inside the policy class, so it
#                can lie in Pi_delta(D)) or "mixture" (outside the class).
# N_WORKERS    : parallel processes (use 1 inside a notebook).
# =============================================================================
DELTA = 4.0
EPSILONS = (0.0005, 0.001)
NS = (20, 50, 80)
SEEDS = 10
GROUND_TRUTHS = ["F T", "F C", "(F T ^ G !C)", "(F C ^ G !T)"]
CANDIDATES = None
EXPERT_RIDGE = 1e-4
PERTURBATION = "projected"
N_WORKERS = os.cpu_count() or 1

FORMULAS = rs.FORMULAS
INDEX = {phi: i for i, phi in enumerate(FORMULAS)}
# candidates in grammar order (the order decides ties)
CAND = [phi for phi in FORMULAS if CANDIDATES is None or phi in set(CANDIDATES)]
B, D = rs.THETA_BOX, rs.D

EXPERT_FILE = "ground_truth_experts_route.json"   # cache of the expert policies
OUT_FILE = (f"ground_truth_perturbation_route_{PERTURBATION}"
            f"{'' if CANDIDATES is None else f'_{len(CAND)}candidates'}_delta{DELTA:g}.csv")
TOL = 1e-7                                        # tolerance for ties / comparisons


# =============================================================================
# 2) LOGICAL IMPLICATION BETWEEN CANDIDATES
# -----------------------------------------------------------------------------
# For the grammar F p / G !p / conjunctions, a formula depends only on which of
# T, S, C occur in the trace. phi |= psi  iff  psi holds on every one of the
# 8 outcomes on which phi holds.
# =============================================================================
_OUTCOMES = list(itertools.product((0, 1), repeat=3))       # (hit T, hit S, hit C)
_TRUTH_TABLE = np.array([[rs.evaluate_dag_on_outcome(o)[rs.FORMULA_ROOT_IDS[phi]]
                          for o in _OUTCOMES] for phi in FORMULAS])


def implies(phi, psi):
    return bool(np.all(~_TRUTH_TABLE[INDEX[phi]] | _TRUTH_TABLE[INDEX[psi]]))


def relation(pick, truth):
    if pick == truth:
        return "= phi*"
    return "implied by phi*" if implies(truth, pick) else "not implied"


# Candidates that imply no other candidate: the only ones either method can pick.
WEAKEST = [phi for phi in CAND
           if not any(psi != phi and implies(phi, psi) for psi in CAND)]


# =============================================================================
# 3) EXPERT POLICY FOR EACH GROUND TRUTH
# -----------------------------------------------------------------------------
# theta*_phi maximizes P_H(phi | pi_theta) - EXPERT_RIDGE * ||theta||^2 over the
# box, by multi-start L-BFGS-B with the exact gradient of RouteSelection.py.
# The unpenalized in-class maximum is computed too, for reference.
# Results are cached in EXPERT_FILE.
# =============================================================================
def _maximize(phi, ridge, model, starts):
    accept = rs.ACCEPT[phi]

    def f(th):
        return -model.value(th, accept) + ridge * th @ th

    def g(th):
        return -model.gradient(th, accept) + 2 * ridge * th

    best = None
    for th0 in starts:
        r = minimize(f, np.asarray(th0, float), jac=g, method="L-BFGS-B",
                     bounds=[(-B, B)] * D,
                     options=dict(maxiter=500, ftol=1e-14, gtol=1e-10))
        if best is None or r.fun < best.fun:
            best = r
    return best.x


def _expert_job(phi):
    model = rs.SatisfactionModel()
    sobol = qmc.Sobol(d=D, scramble=True, seed=0).random(32) * 2 * B - B
    starts = [np.zeros(D), rs.THETA_TRUE] + list(sobol)
    theta_max = _maximize(phi, 0.0, model, starts)
    theta = _maximize(phi, EXPERT_RIDGE, model, starts + [theta_max])
    accept = rs.ACCEPT[phi]
    return phi, dict(theta=[float(v) for v in theta],
                     value=model.value(theta, accept),
                     max_value=model.value(theta_max, accept))


def compute_experts(truths):
    cache = {}
    if os.path.exists(EXPERT_FILE):
        with open(EXPERT_FILE) as fh:
            stored = json.load(fh)
        if stored.get("ridge") == EXPERT_RIDGE:
            cache = stored["experts"]
    todo = [phi for phi in truths if phi not in cache]
    if todo:
        print(f"Computing expert policies for {len(todo)} formulas ...", flush=True)
        with Pool(min(N_WORKERS, len(todo))) as pool:
            for phi, res in pool.imap_unordered(_expert_job, todo):
                cache[phi] = res
        with open(EXPERT_FILE, "w") as fh:
            json.dump(dict(ridge=EXPERT_RIDGE, experts=cache), fh, indent=1)
    return {phi: cache[phi] for phi in truths}


def expert_policy(theta, eps):
    """pi_mix(a|s) = (1 - eps) pi_theta(a|s) + eps / |A(s)| at every policy state."""
    pi, _ = rs.policy_probs(theta)
    uniform = rs.POL_MASK / rs.POL_MASK.sum(axis=1, keepdims=True)
    return (1 - eps) * pi + eps * uniform


def expected_counts(pi_pol):
    """Expected state-action counts of ONE trajectory under pi_pol (exact)."""
    nus = rs.forward_distributions(rs.product_policy(pi_pol))
    visits = nus[:rs.H].sum(axis=0)                  # expected visits per product state
    occ = np.zeros(rs.N_POL)
    np.add.at(occ, rs.PROD_POL[rs.NON_ABS], visits[rs.NON_ABS])
    return occ[:, None] * pi_pol


def demonstrator(theta_star, eps):
    """Policy table and parameter (None if outside the class) of the demonstrator."""
    if eps == 0:
        return rs.policy_probs(theta_star)[0], theta_star
    pi_mix = expert_policy(theta_star, eps)
    if PERTURBATION == "mixture":
        return pi_mix, None
    theta_eps = mle_box(expected_counts(pi_mix))     # in-class projection of pi_mix
    return rs.policy_probs(theta_eps)[0], theta_eps


def true_values(pi_pol):
    """Exact P_H(phi | expert) for every candidate (forward pass, Eq. (11)-(12))."""
    nus = rs.forward_distributions(rs.product_policy(pi_pol))
    return {phi: float(nus[rs.H] @ rs.ACCEPT[phi]) for phi in FORMULAS}


# =============================================================================
# 4) DEMONSTRATIONS AND MAXIMUM-LIKELIHOOD ESTIMATE
# -----------------------------------------------------------------------------
# Same simulator as RouteSelection.generate_demonstrations, but for any policy
# table (the perturbed expert is not of the form pi_theta).
# =============================================================================
def demonstrations(pi_pol, n_trajs, rng):
    counts = np.zeros((rs.N_POL, rs.N_SLOTS))
    for _ in range(n_trajs):
        i = rs.START_STATE
        for _ in range(rs.H):
            if rs.ABSORBING[i]:
                break
            j = rs.PROD_POL[i]
            k = rng.choice(rs.N_SLOTS, p=pi_pol[j])
            counts[j, k] += 1
            i = rs.NXT[i, k, rng.choice(3, p=rs.PRB[i, k])]
    return counts


def mle_box(counts):
    """MLE of Eq. (5) over the box |theta_i| <= THETA_BOX (concave problem)."""
    r = minimize(lambda th: -rs.loglik(th, counts), np.zeros(D),
                 jac=lambda th: -rs.loglik_grad_hess(th, counts)[0],
                 method="L-BFGS-B", bounds=[(-B, B)] * D,
                 options=dict(maxiter=5000, ftol=1e-15, gtol=1e-9))
    return r.x


# =============================================================================
# 5) WORST CASE OVER Pi_delta(D) WITH PRUNING
# -----------------------------------------------------------------------------
# Same problem, IPOPT options and starting-point scheme as
# RouteSelection.worst_case_multistart (see the notes at the top for the two
# changes). Returns the worst-case value, or eliminated = True as soon as an
# IPOPT run goes below `stop_below`.
# =============================================================================
START_RIDGE = 1.0   # added to the Fisher information, for starting points only


def worst_case(phi, counts, theta_hat, model, stop_below=-np.inf, seed=0,
               batch_size=8, min_starts=27, max_starts=120, min_hits=3,
               value_tol=1e-7, max_iter=300):
    accept = rs.ACCEPT[phi]
    ll_min = rs.loglik(theta_hat, counts) - DELTA

    class NLP:
        def objective(self, theta):
            return model.value(theta, accept)

        def gradient(self, theta):
            return model.gradient(theta, accept)

        def constraints(self, theta):
            return np.array([rs.loglik(theta, counts) - ll_min])

        def jacobian(self, theta):
            return rs.loglik_grad_hess(theta, counts)[0]

    problem = cyipopt.Problem(n=D, m=1, problem_obj=NLP(),
                              lb=np.full(D, -B), ub=np.full(D, B),
                              cl=np.array([0.0]), cu=np.array([1e19]))
    for key, val in (("sb", "yes"), ("print_level", 0), ("max_iter", max_iter),
                     ("tol", 1e-9), ("acceptable_tol", 1e-7),
                     ("mu_strategy", "adaptive"),
                     ("hessian_approximation", "limited-memory")):
        problem.add_option(key, val)

    # starting points: MLE, rays along principal / descent / Sobol directions
    _, hess = rs.loglik_grad_hess(theta_hat, counts)
    cov = np.linalg.inv(-hess + START_RIDGE * np.eye(D))
    eigval, eigvec = np.linalg.eigh(cov)
    sqrt_cov = eigvec @ np.diag(np.sqrt(np.clip(eigval, 0, None)))

    def along(direction, frac):
        return theta_hat + frac * rs._ray_length(theta_hat, direction, counts,
                                                 ll_min) * direction

    directions = [s * sqrt_cov[:, i] for i in range(D) for s in (1, -1)]
    descent = -cov @ model.gradient(theta_hat, accept)
    if np.linalg.norm(descent) > 0:
        directions.append(descent)
    pending = [theta_hat.copy()]
    for d in directions:
        pending += [along(d, 0.5), along(d, 0.95)]
    sobol = qmc.Sobol(d=D + 1, scramble=True, seed=seed)

    values, n_tried, best = [], 0, np.inf
    while n_tried < max_starts:
        if not pending:
            for row in np.clip(sobol.random(batch_size), 1e-12, 1 - 1e-12):
                pending.append(along(sqrt_cov @ norm.ppf(row[:D]),
                                     0.02 + 0.96 * row[D] ** (1.0 / D)))
        batch, pending = pending[:batch_size], pending[batch_size:]
        best_before = best
        for theta0 in batch:
            if n_tried >= max_starts:
                break
            n_tried += 1
            try:
                theta_opt, info = problem.solve(np.asarray(theta0, float))
            except Exception:
                continue
            if (info["status"] not in (0, 1)
                    or rs.loglik(theta_opt, counts) < ll_min - 1e-6):
                continue
            val = model.value(theta_opt, accept)
            values.append(val)
            best = min(best, val)
            if best < stop_below - TOL:                 # cannot win: prune
                return dict(val=best, eliminated=True, n_starts=n_tried)
        hits = int(np.sum(np.asarray(values) <= best + value_tol))
        if n_tried >= min_starts and hits >= min_hits and best >= best_before - value_tol:
            break
    if not values:
        raise RuntimeError(f"IPOPT failed from every start for {phi}.")
    return dict(val=best, eliminated=False, n_starts=n_tried)


def robust_pick(counts, theta_hat, nominal, model, seed):
    """argmax over WEAKEST of the worst-case value (first-in-list ties)."""
    best_phi, best_val, n_starts = None, -np.inf, 0
    for phi in sorted(WEAKEST, key=lambda p: (-nominal[p], INDEX[p])):
        if nominal[phi] < best_val - TOL:      # worst case <= nominal: cannot win
            break
        r = worst_case(phi, counts, theta_hat, model, stop_below=best_val, seed=seed)
        n_starts += r["n_starts"]
        if r["eliminated"]:
            continue
        if (r["val"] > best_val + TOL
                or (abs(r["val"] - best_val) <= TOL and INDEX[phi] < INDEX[best_phi])):
            best_phi, best_val = phi, r["val"]
    return best_phi, best_val, n_starts


# =============================================================================
# 6) ONE DATASET: expert -> demonstrations -> nominal and robust picks
# =============================================================================
_MODEL = None


def run_one(task):
    global _MODEL
    if _MODEL is None:
        _MODEL = rs.SatisfactionModel()
    truth, eps, n, seed, theta_star = task
    t0 = time.time()
    pi, theta_dem = demonstrator(np.asarray(theta_star), eps)
    true = true_values(pi)
    rng = np.random.default_rng([seed, int(round(1e6 * eps)), n, INDEX[truth]])
    counts = demonstrations(pi, n, rng)
    theta_hat = mle_box(counts)

    nominal = _MODEL.all_values(theta_hat)
    f_nom = max(CAND, key=nominal.get)                   # first maximum in the list
    assert f_nom in WEAKEST, "monotonicity violated"
    f_rob, v_rob, n_starts = robust_pick(counts, theta_hat, nominal, _MODEL, seed)

    ll_hat = rs.loglik(theta_hat, counts)
    in_set = ""                      # demonstrator's parameter in Pi_delta(D)?
    if theta_dem is not None:
        in_set = int(ll_hat - rs.loglik(theta_dem, counts) <= DELTA)
    # the unperturbed optimal expert theta* in Pi_delta(D)?
    star_in_set = int(ll_hat - rs.loglik(np.asarray(theta_star), counts) <= DELTA)
    return dict(truth=truth, eps=eps, N=n, seed=seed,
                nominal_pick=f_nom, nominal_value=nominal[f_nom],
                nominal_true=true[f_nom], nominal_relation=relation(f_nom, truth),
                robust_pick=f_rob, robust_value=v_rob,
                robust_true=true[f_rob], robust_relation=relation(f_rob, truth),
                expert_in_set=in_set, theta_star_in_set=star_in_set,
                ipopt_starts=n_starts, seconds=round(time.time() - t0, 2))


FIELDS = ["truth", "eps", "N", "seed", "nominal_pick", "nominal_value",
          "nominal_true", "nominal_relation", "robust_pick", "robust_value",
          "robust_true", "robust_relation", "expert_in_set", "theta_star_in_set",
          "ipopt_starts", "seconds"]


def _key(truth, eps, n, seed):
    return (truth, round(float(eps), 6), int(n), int(seed))


def load_rows():
    if not os.path.exists(OUT_FILE):
        return []
    with open(OUT_FILE) as fh:
        return list(csv.DictReader(fh))


def run(truths, experts):
    done = {_key(r["truth"], r["eps"], r["N"], r["seed"]) for r in load_rows()}
    tasks = [(phi, eps, n, s, experts[phi]["theta"])
             for eps in EPSILONS for n in NS for phi in truths for s in range(SEEDS)
             if _key(phi, eps, n, s) not in done]
    print(f"{len(tasks)} datasets to run ({len(done)} already in {OUT_FILE}), "
          f"{N_WORKERS} workers", flush=True)
    if not tasks:
        return
    new_file = not os.path.exists(OUT_FILE)
    t0 = time.time()
    with open(OUT_FILE, "a", newline="") as fh, Pool(N_WORKERS) as pool:
        writer = csv.DictWriter(fh, fieldnames=FIELDS)
        if new_file:
            writer.writeheader()
        for k, row in enumerate(pool.imap_unordered(run_one, tasks), 1):
            writer.writerow(row)
            fh.flush()
            if k % 25 == 0 or k == len(tasks):
                rate = (time.time() - t0) / k
                print(f"  {k}/{len(tasks)} done, about "
                      f"{rate * (len(tasks) - k) / 60:.0f} min left", flush=True)


# =============================================================================
# 7) OUTPUT
# -----------------------------------------------------------------------------
# Expert table, then Step 1 (eps = 0, largest N): the most frequent pick of each
# method for every phi*; then averages over all phi* for every (eps, N).
# =============================================================================
def print_experts(experts):
    print("\n=== Expert policy for each ground truth phi* ===")
    print(f"{'phi*':24s} {'P(phi*|expert)':>14s} {'in-class max':>12s}   "
          "theta* (progress, follow_road, enter_C, stop)")
    for phi, e in experts.items():
        print(f"{phi:24s} {e['value']:14.4f} {e['max_value']:12.4f}   "
              f"{np.round(e['theta'], 2)}")


def _most_common(values):
    (v, c), = collections.Counter(values).most_common(1)
    return v, c / len(values)


def summarize(truths):
    rows = [r for r in load_rows() if r["truth"] in truths]
    for r in rows:
        r["eps"], r["N"] = float(r["eps"]), int(r["N"])
        for k in ("nominal_value", "nominal_true", "robust_value", "robust_true"):
            r[k] = float(r[k])
    if not rows:
        print("No results yet.")
        return
    eps_list = sorted({r["eps"] for r in rows})
    n_list = sorted({r["N"] for r in rows})

    n1 = n_list[-1]
    print(f"\n=== Step 1: optimal expert (eps = 0), N = {n1}: most frequent pick "
          "(share of datasets) ===")
    print(f"{'phi*':24s} | {'nominal pick':22s} {'relation':16s} | "
          f"{'robust pick':22s} {'relation':16s}")
    for phi in truths:
        g = [r for r in rows if r["truth"] == phi and r["eps"] == 0 and r["N"] == n1]
        if not g:
            continue
        cells = []
        for tag in ("nominal", "robust"):
            pick, share = _most_common([r[f"{tag}_pick"] for r in g])
            cells.append(f"{pick + f' ({share:.0%})':22s} {relation(pick, phi):16s}")
        print(f"{phi:24s} | " + " | ".join(cells))

    print("\n=== Averages over ground truths (nominal / robust) ===")
    print("  exact    : pick = phi*, over the phi* either method can pick "
          f"({', '.join(p for p in WEAKEST if p in truths)})")
    print("  phi*|=pick: pick is phi* or a weaker formula implied by phi*, all phi*")
    print("  true     : true satisfaction of the pick under the expert's policy")
    print("  over     : reported value of the pick > its true satisfaction")
    print("  in set   : demonstrator's parameter in Pi_delta(D)")
    print(f"{'eps':>5s} {'N':>4s} {'sets':>5s} | {'exact':>11s} | {'phi*|=pick':>11s} | "
          f"{'true':>11s} | {'over':>11s} | {'in set':>6s}")
    for eps in eps_list:
        for n in n_list:
            g = [r for r in rows if r["eps"] == eps and r["N"] == n]
            if not g:
                continue
            gc = [r for r in g if r["truth"] in WEAKEST]

            def pair(f, rs_=g):
                if not rs_:
                    return f"{'-':>11s}"
                a = np.mean([f(r, "nominal") for r in rs_])
                b = np.mean([f(r, "robust") for r in rs_])
                return f"{a:5.2f}/{b:5.2f}"

            flags = [int(r["expert_in_set"]) for r in g if r["expert_in_set"] != ""]
            cov = f"{np.mean(flags):6.2f}" if flags else f"{'-':>6s}"
            print(f"{eps:5.2f} {n:4d} {len(g):5d} | "
                  f"{pair(lambda r, t: r[f'{t}_relation'] == '= phi*', gc)} | "
                  f"{pair(lambda r, t: r[f'{t}_relation'] != 'not implied')} | "
                  f"{pair(lambda r, t: r[f'{t}_true'])} | "
                  f"{pair(lambda r, t: r[f'{t}_value'] > r[f'{t}_true'] + 1e-9)} | {cov}")


