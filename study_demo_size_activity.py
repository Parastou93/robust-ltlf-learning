"""Example 2 (physical activity): effect of the number of demonstration days.

The demonstrations are generated by a known mixture (demo_weights), so the
true satisfaction probability of every candidate formula under the
demonstrator's policy can be computed exactly. For each number of days, this
script draws independent demonstration sets and compares, for the nominal and
the robust method, the value reported for the selected formula with its true
satisfaction probability, and records whether each method selects the formula
with the highest true satisfaction probability.

Put this file next to Daily_Physical_Activity.py.
Output: study_demo_size_activity.csv
"""
import csv
import time
from dataclasses import replace

import numpy as np

import Daily_Physical_Activity as dp

SIZES = (10, 30, 100)
N_SETS = 50
TOL = 1e-9


def main():
    rows = []
    t0 = time.time()
    for n in SIZES:
        for s in range(N_SETS):
            result = dp.run(replace(dp.SETTINGS, days=n, seed=1000 + s),
                            save=False, verbose=False)
            by = {r["name"]: r for r in result["rankings"]}
            f_nom = max(by, key=lambda k: by[k]["nominal"])
            f_rob = max(by, key=lambda k: by[k]["worst_case_ipopt"])
            f_best = max(by, key=lambda k: by[k]["demo_policy_probability"])
            rows.append(dict(days=n, set=s, best_true_formula=f_best,
                             nominal_winner=f_nom, nominal_value=by[f_nom]["nominal"],
                             nominal_true=by[f_nom]["demo_policy_probability"],
                             robust_winner=f_rob, robust_value=by[f_rob]["worst_case_ipopt"],
                             robust_true=by[f_rob]["demo_policy_probability"]))
        print(f"days = {n} done ({time.time() - t0:.0f} s)", flush=True)

    with open("study_demo_size_activity.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    print(f"\n{'days':>5} {'robust<=true':>13} {'nominal>true':>13} "
          f"{'robust selects best':>20} {'nominal selects best':>21}")
    for n in SIZES:
        g = [r for r in rows if r["days"] == n]
        rob_ok = np.mean([r["robust_value"] <= r["robust_true"] + TOL for r in g])
        nom_over = np.mean([r["nominal_value"] > r["nominal_true"] + TOL for r in g])
        rob_best = np.mean([r["robust_winner"] == r["best_true_formula"] for r in g])
        nom_best = np.mean([r["nominal_winner"] == r["best_true_formula"] for r in g])
        print(f"{n:>5} {rob_ok:>12.0%} {nom_over:>13.0%} {rob_best:>19.0%} {nom_best:>20.0%}")


if __name__ == "__main__":
    main()
